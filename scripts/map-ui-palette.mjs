import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(root, "artifacts/up-dash/src");
const colors = {
  green: "good",
  emerald: "good",
  teal: "good",
  lime: "good",
  red: "bad",
  rose: "bad",
  pink: "bad",
  fuchsia: "bad",
  amber: "warn",
  yellow: "warn",
  orange: "warn",
  blue: "chart-line",
  sky: "chart-line",
  cyan: "chart-line",
  indigo: "chart-line",
  violet: "chart-secondary",
  purple: "chart-secondary",
  gray: "muted",
  zinc: "muted",
  slate: "muted",
  neutral: "muted",
  stone: "muted",
};
const utilities = new Map();
function scan(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) scan(file);
    else if (file.endsWith(".tsx")) {
      const source = fs.readFileSync(file, "utf8");
      for (const match of source.matchAll(
        /(?<![\w:-])((?:(?:dark|hover|focus):)*)(text|bg|border|ring|fill|stroke)-(green|emerald|teal|lime|red|rose|pink|fuchsia|amber|yellow|orange|blue|sky|cyan|indigo|violet|purple|gray|zinc|slate|neutral|stone)-(\d+)(?:\/(\d+))?/g,
      )) {
        utilities.set(match[0], match.slice(1));
      }
    }
  }
}
scan(sourceRoot);
const scope =
  ':where(.up-app, [role="dialog"], [role="alertdialog"], [role="tooltip"], [data-up-surface="popover"])';
let css =
  "/* Generated by scripts/map-ui-palette.mjs. Legacy utility colors use UP Glass tokens. */\n";
for (const [utility, [variants, property, color, shade, opacity]] of [
  ...utilities,
].sort(([a], [b]) => a.localeCompare(b))) {
  const token = `var(--up-${colors[color]})`;
  const alpha = opacity
    ? Number(opacity)
    : property === "bg" && (Number(shade) < 300 || Number(shade) > 700)
      ? 13
      : 100;
  const value =
    alpha === 100
      ? token
      : `color-mix(in srgb, ${token} ${alpha}%, transparent)`;
  const declaration = {
    text: "color",
    bg: "background-color",
    border: "border-color",
    ring: "--tw-ring-color",
    fill: "fill",
    stroke: "stroke",
  }[property];
  const pseudo = variants.includes("hover:")
    ? ":hover"
    : variants.includes("focus:")
      ? ":focus"
      : "";
  css += `${variants.includes("dark:") ? ".dark " : ""}${scope} [class~="${utility}"]${pseudo} { ${declaration}: ${value}; }\n`;
}
fs.writeFileSync(path.join(sourceRoot, "styles/up-glass-palette.css"), css);
console.log(
  `UP Glass: ${utilities.size} utilitários de cor ligados aos tokens do kit.`,
);
